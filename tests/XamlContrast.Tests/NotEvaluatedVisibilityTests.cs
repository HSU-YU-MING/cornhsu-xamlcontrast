using XamlContrast.Core;

namespace XamlContrast.Tests;

/// <summary>
/// 「放過的東西一律要現形」在兩份給人看的報告上（console 與 --md 的 PR 留言）：
/// 無法解析（含原因細目）、跳過、死 setter、停用態豁免、壓掉、解析失敗、無效 ignore、
/// 非預設門檻 —— 少印一種，讀者就會以為表上的就是全部（CLAUDE.md：豁免、壓抑、跳過、
/// 解析失敗全部有計數器且一律印出來；「更乾淨的報告」不是改進）。
/// </summary>
public class NotEvaluatedVisibilityTests
{
    private static AuditResult RunEverySkipShape()
    {
        using var fx = new Fixture();
        fx.File("Broken.xaml", "<Grid><未閉合");
        fx.File(ToolConfig.FileName, """{ "thresholds": { "normalText": 7.0 } }""");
        fx.File("Main.xaml", """
            <Grid xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml" Background="#000000">
              <Grid.Resources>
                <Style x:Key="Btn" TargetType="Button">
                  <Setter Property="Background" Value="#000000"/>
                  <Setter Property="Foreground" Value="#FFFFFF"/>
                  <Style.Triggers>
                    <Trigger Property="IsEnabled" Value="False">
                      <Setter Property="Foreground" Value="#303030"/>
                    </Trigger>
                  </Style.Triggers>
                </Style>
                <Style x:Key="Dead" TargetType="CheckBox">
                  <Setter Property="Background" Value="#FFFFFF"/>
                  <Setter Property="Foreground" Value="#FFFFFF"/>
                  <Setter Property="Template">
                    <Setter.Value>
                      <ControlTemplate TargetType="CheckBox">
                        <Border Background="#FFFFFF"><Path Stroke="#FFFFFF"/></Border>
                      </ControlTemplate>
                    </Setter.Value>
                  </Setter>
                </Style>
              </Grid.Resources>
              <TextBlock Foreground="#FFFFFF" Text="ok"/>
              <TextBlock Foreground="#333333" Text="fail"/>
              <Border Background="{Binding UserColour}"><TextBlock Foreground="#FFFFFF" Text="bound"/></Border>
              <TextBlock Opacity="0" Foreground="#FFFFFF" Text="skipped"/>
              <!-- xamlcontrast-ignore: watermark -->
              <TextBlock Foreground="#111111" Text="suppressed"/>
              <!-- xamlcontrast-ignore -->
              <TextBlock Foreground="#FFFFFF" Text="ignore without a reason"/>
            </Grid>
            """);
        var cfg = ToolConfig.Load(fx.Root);
        return Auditor.Run(fx.Root, PaletteDetector.Detect(fx.Root, cfg), cfg);
    }

    [Fact]
    public void ConsoleNamesEverythingItDidNotEvaluate()
    {
        var console = Report.ToConsole(RunEverySkipShape());
        Assert.Contains("!! non-default thresholds: normal 7, large 3, fail-factor 0.67", console);
        Assert.Contains("unresolved (colour bound at runtime / gradient / key not in palette): 1 | skipped (translucent, invisible): 1", console);
        Assert.Contains("unresolved by reason: bound-or-gradient 1", console);
        Assert.Contains("excluded 1 style pair(s): template has no Foreground consumer", console);
        Assert.Contains("exempted 1 disabled-state pair(s)", console);
        Assert.Contains("suppressed 1 pair(s) via xamlcontrast-ignore comments", console);
        Assert.Contains("!! parse failed: Broken.xaml", console);
        Assert.Contains("!! Main.xaml:", console);
        Assert.Contains("xamlcontrast-ignore without a reason is invalid (not suppressed)", console);
    }

    [Fact]
    public void MarkdownNamesEverythingItDidNotEvaluate()
    {
        var md = Report.ToMarkdown(RunEverySkipShape(), exitCode: 1);
        Assert.Contains("**Non-default thresholds** — normal 7, large 3, fail-factor 0.67.", md);
        Assert.Contains("**Not evaluated:** 1 unresolved (bound-or-gradient 1) · 1 skipped (translucent, invisible) · " +
                        "1 excluded (dead Foreground setter) · 1 exempted (IsEnabled=False; WCAG 1.4.3) · " +
                        "1 suppressed via xamlcontrast-ignore", md);
        Assert.Contains("**Parse failed:** Broken.xaml", md);
        Assert.Contains("— this file is missing from the audit above.", md);
        Assert.Contains("xamlcontrast-ignore without a reason is invalid", md);
        // 警告框排在落差表之後、頁尾之前 —— 但一定在報告裡
        Assert.True(md.IndexOf("**Parse failed:**", StringComparison.Ordinal)
                    < md.IndexOf("Generated by XamlContrast", StringComparison.Ordinal));
    }
}
